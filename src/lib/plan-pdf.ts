import { jsPDF } from "jspdf";
import resources from "@/data/ct-resources.json";
import type { PlanShape, StepRow } from "@/lib/plan-types";
import { SITE_HOST } from "@/lib/site";

type Resource = (typeof resources)[number];

const resourceMap = new Map(resources.map((r) => [r.id, r]));

export function findResource(id: string | null): Resource | null {
  if (!id) return null;
  return resourceMap.get(id) ?? null;
}

export interface PlanPdfInput {
  plan: PlanShape;
  steps: StepRow[];
  generatedAt?: string | null;
}

export function generatePlanPdf({ plan, steps, generatedAt }: PlanPdfInput): Blob {
  const doc = new jsPDF({ unit: "pt", format: "letter", orientation: "portrait" });
  const margin = 40;
  let y = margin;
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const maxY = pageHeight - margin;
  const lineWidth = pageWidth - margin * 2;

  const addText = (text: string, opts: { size?: number; bold?: boolean; color?: string; lineHeight?: number } = {}) => {
    const { size = 11, bold = false, color = "#000000", lineHeight = 1.4 } = opts;
    doc.setFontSize(size);
    doc.setFont("helvetica", bold ? "bold" : "normal");
    doc.setTextColor(color);
    const split = doc.splitTextToSize(text, lineWidth);
    const neededHeight = split.length * size * lineHeight;
    if (y + neededHeight > maxY) {
      doc.addPage();
      y = margin;
    }
    doc.text(split, margin, y);
    y += neededHeight;
  };

  // Header
  addText("Wake Up Hartford — Your 30-Day Stabilization Plan", { size: 16, bold: true, lineHeight: 1.3 });
  y += 6;
  if (generatedAt) {
    addText(`Created on ${new Date(generatedAt).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" })}`, {
      size: 10,
      color: "#444444",
    });
    y += 6;
  }

  addText(plan.priority_summary, { size: 11, lineHeight: 1.5 });
  y += 12;

  // Crisis flags
  if (plan.crisis_flags && plan.crisis_flags.length > 0) {
    addText("Right now — immediate support", { size: 13, bold: true });
    y += 4;
    for (const flag of plan.crisis_flags) {
      addText(`• ${flag.note}`, { size: 10 });
      addText(`  Hotline: ${flag.hotline}`, { size: 10, bold: true });
      y += 4;
    }
    y += 8;
  }

  // Progress summary
  const total = steps.length;
  const done = steps.filter((s) => s.completed_at).length;
  addText(`Progress: ${done} of ${total} steps completed`, { size: 11, bold: true });
  y += 16;

  // Steps by week
  const stepsByWeek = new Map<number, StepRow[]>();
  for (const s of steps) {
    const arr = stepsByWeek.get(s.week) ?? [];
    arr.push(s);
    stepsByWeek.set(s.week, arr);
  }

  for (let week = 1; week <= 4; week++) {
    const weekMeta = plan.weeks.find((w) => w.week === week);
    const weekSteps = stepsByWeek.get(week) ?? [];
    if (!weekMeta && weekSteps.length === 0) continue;

    addText(`Week ${week}${weekMeta?.focus ? ` — ${weekMeta.focus}` : ""}`, { size: 13, bold: true });
    y += 6;

    if (weekSteps.length === 0) {
      addText("No steps for this week.", { size: 10, color: "#666666" });
      y += 12;
      continue;
    }

    for (const step of weekSteps) {
      const doneMark = step.completed_at ? "[x]" : "[ ]";
      addText(`${doneMark} ${step.title}`, { size: 11, bold: true });
      if (step.detail) {
        addText(step.detail, { size: 10, color: "#333333" });
      }
      const resource = findResource(step.resource_id);
      if (resource) {
        const info = [`Resource: ${resource.name}`, resource.phone ? `Phone: ${resource.phone}` : null, resource.url ? `URL: ${resource.url}` : null]
          .filter(Boolean)
          .join("  ");
        addText(info, { size: 9, color: "#444444" });
      }
      y += 8;
    }
    y += 12;
  }

  // Footer
  const footer = `This plan was generated by Wake Up Hartford. Visit ${SITE_HOST} to update your progress.`;
  doc.setFontSize(9);
  doc.setTextColor("#666666");
  const footerSplit = doc.splitTextToSize(footer, lineWidth);
  const footerY = pageHeight - margin - footerSplit.length * 9;
  doc.text(footerSplit, margin, footerY);

  return doc.output("blob");
}
